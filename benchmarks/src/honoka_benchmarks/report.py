"""Render benchmark results as Markdown and keep the README's results section current."""

import json
from pathlib import Path

from honoka_benchmarks.frameworks import Framework

START = "<!-- benchmark-results:start -->"
END = "<!-- benchmark-results:end -->"

TEMPLATE = f"""# Benchmarks

Compares honoka with other Python web frameworks on a realistic API under heavy load. The
numbers below are regenerated by the runner; everything outside the markers is hand-written.

## What is measured

A small shop API that every framework implements (`src/honoka_benchmarks/apps/`):

| Endpoint | Work done |
|---|---|
| `GET /products?category=&sort=&page=&per_page=` | validates 6 query parameters, filters and sorts about 600 of 5,000 products, simulated 2 ms database call, serializes 50 products (about 13 KB of JSON) |
| `GET /products/{{id}}` | path parameter, 2 ms database call, small JSON |
| `POST /orders` | HMAC token check, validates a nested body (1-5 lines, ranges, a pattern), prices it, 3 ms database call |
| `GET /orders/{{id}}` | HMAC token check, 2 ms database call |
| every request | CORS (`Origin` header) and an `x-request-id` response header |

Load scenarios (`src/honoka_benchmarks/mix.py`):

- **mixed**: 35% list, 35% detail, 12% create order, 8% order detail, 10% bad requests (404, 401,
  invalid body, invalid query). This is the closest to production traffic.
- **list-heavy**: only the list endpoint (large responses, most CPU in serialization).
- **write-heavy**: only order creation (auth, nested validation, pricing).

## How to compare fairly

- The business logic (`shop.py`), the dataset, the database latency and the request mix are
  shared. Frameworks differ only in routing, parsing, validation, middleware and serialization.
- Each app is written the way that framework's documentation does it, with its own default JSON
  encoder. honoka uses `MsgspecCodec`, Litestar uses msgspec natively, the rest use their
  defaults. Frameworks without built-in validation (Starlette, Falcon, BlackSheep, Robyn, the raw
  baselines) validate with msgspec, which is the cheapest correct option.
- `raw-rsgi` and `raw-asgi` are hand-written apps: the floor that a framework on the same
  interface adds its own overhead to.
- Each framework runs in **one worker process** by default. With several workers the kernel
  spreads connections unevenly and differently on every start; a 4-worker run varied up to 3.7x
  between passes for the same app (`results/*-4workers-noisy.json`). One process measures
  per-process efficiency, and throughput then grows with the number of workers. Use `--workers`
  to try more, and read the spread table before trusting a difference.
- Throughput on a laptop is noisy (power management, other processes). **Server CPU time per
  request** is the steadiest number: it does not depend on how busy the client keeps the server.
  The runner repeats everything 3 times with the framework order rotated and reports the median.
- Before any load, each app must answer 12 contract requests exactly like the reference logic
  (`conformance.py`); an app that does not conform is reported as not measured.
- The load generator is closed loop (a fixed number of keep-alive connections), so it measures
  peak throughput and latency at saturation, not latency at a fixed arrival rate. "Client CPU"
  shows how busy each generator process was: if it is near 100% the generator, not the server,
  is the limit.
- A single machine runs both client and server, so absolute numbers are only comparable within
  one table. Run it on your own hardware before drawing conclusions.

## Run it

```sh
uv sync --all-packages
uv run python -m honoka_benchmarks.run                      # everything, about 35 minutes
uv run python -m honoka_benchmarks.run --frameworks honoka fastapi --seconds 10
uv run python -m honoka_benchmarks.run --check-only         # conformance only
```

Raw numbers of every run are kept in `results/*.json`.

## Latest results

{START}
_No run yet._
{END}
"""


def _cell(
    results: dict[str, dict[str, dict[str, object]]], fw: str, scenario: str, key: str
) -> object:
    return results.get(fw, {}).get(scenario, {}).get(key)


def _table(
    results: dict[str, dict[str, dict[str, object]]],
    frameworks: list[Framework],
    scenarios: list[str],
    key: str,
    fmt: str,
) -> list[str]:
    lines = ["| framework | " + " | ".join(scenarios) + " |", "|---|" + "---:|" * len(scenarios)]
    for fw in frameworks:
        cells = []
        for scenario in scenarios:
            value = _cell(results, fw.name, scenario, key)
            cells.append(fmt.format(value) if isinstance(value, (int, float)) else "n/a")
        lines.append(f"| {fw.name} | " + " | ".join(cells) + " |")
    return lines


def _share_table(
    results: dict[str, dict[str, dict[str, object]]],
    frameworks: list[Framework],
    scenarios: list[str],
) -> list[str]:
    lines = [
        "| framework (vs its raw baseline) | " + " | ".join(scenarios) + " |",
        "|---|" + "---:|" * len(scenarios),
    ]
    for fw in frameworks:
        if fw.baseline is None:
            continue
        cells = []
        for scenario in scenarios:
            rps = _cell(results, fw.name, scenario, "rps")
            floor = _cell(results, fw.baseline, scenario, "rps")
            if isinstance(rps, (int, float)) and isinstance(floor, (int, float)) and floor > 0:
                cells.append(f"{rps / floor * 100:.0f}%")
            else:
                cells.append("n/a")
        lines.append(f"| {fw.name} (vs {fw.baseline}) | " + " | ".join(cells) + " |")
    return lines


def render(
    meta: dict[str, object],
    results: dict[str, dict[str, dict[str, object]]],
    frameworks: list[Framework],
    scenarios: list[str],
) -> str:
    versions = meta.get("versions", {})
    version_text = (
        ", ".join(f"{k} {v}" for k, v in versions.items()) if isinstance(versions, dict) else ""
    )
    lines = [
        f"Run on {meta['date']} at commit `{meta['git']}`.",
        "",
        f"- Machine: {meta['machine']}",
        f"- Python {meta['python']}, Granian {meta['granian']}",
        f"- Server: {meta['server']}",
        f"- Load: {meta['load']}",
        f"- Versions: {version_text}",
        "",
    ]
    sections = (
        ("Requests per second (higher is better)", "rps", "{:,.0f}"),
        ("p99 latency in ms (lower is better)", "p99_ms", "{:.1f}"),
        ("p50 latency in ms", "p50_ms", "{:.1f}"),
        (
            "Server CPU time per request in ms (lower is better)",
            "server_cpu_ms_per_request",
            "{:.3f}",
        ),
        ("Server memory after the run in MB", "rss_mb", "{:.0f}"),
        (
            "Spread of requests per second across the passes, max / min (close to 1.00 means a stable result)",
            "rps_spread",
            "{:.2f}x",
        ),
        ("Unexpected responses (should be 0)", "unexpected", "{:.0f}"),
        (
            "Load generator CPU in % of one core per process (near 100 means the client is the limit)",
            "client_cpu_pct",
            "{:.0f}",
        ),
    )
    for index, (title, key, fmt) in enumerate(sections):
        lines += [f"### {title}", "", *_table(results, frameworks, scenarios, key, fmt), ""]
        if index == 0:
            lines += [
                "### Share of the raw baseline on the same interface",
                "",
                *_share_table(results, frameworks, scenarios),
                "",
            ]
    skipped = [
        f"- {fw}: {cells['*'].get('error', 'no result')}"
        for fw, cells in results.items()
        if "*" in cells and "error" in cells["*"]
    ]
    if skipped:
        lines += ["### Not measured", "", *skipped, ""]
    return "\n".join(lines).rstrip() + "\n"


def update_readme(
    path: Path,
    meta: dict[str, object],
    results: dict[str, dict[str, dict[str, object]]],
    frameworks: list[Framework],
    scenarios: list[str],
) -> None:
    block = render(meta, results, frameworks, scenarios)
    text = path.read_text() if path.exists() else TEMPLATE
    if START not in text or END not in text:
        text = text.rstrip() + f"\n\n## Latest results\n\n{START}\n_No run yet._\n{END}\n"
    head, _, rest = text.partition(START)
    _, _, tail = rest.partition(END)
    path.write_text(f"{head}{START}\n{block}{END}{tail}")


def main() -> None:
    """Rebuild the README's results from a saved run: `python -m honoka_benchmarks.report FILE`."""
    import sys

    from honoka_benchmarks.frameworks import FRAMEWORKS

    saved = json.loads(Path(sys.argv[1]).read_text())
    results = saved["results"]
    frameworks = [f for f in FRAMEWORKS if f.name in results]
    scenarios = [s for s in next(iter(v for v in results.values() if "*" not in v), {}) if s != "*"]
    readme = Path(__file__).resolve().parents[2] / "README.md"
    update_readme(readme, saved["meta"], results, frameworks, scenarios)
    print(f"updated {readme}")


if __name__ == "__main__":
    main()
